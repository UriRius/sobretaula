insert into public.visit_participants (visit_id, group_id, user_id, joined_at)
select sv.id, sv.group_id, p.user_id, sv.visit_date + time '22:45'
from seed_visits sv
cross join lateral unnest(sv.participants) as p(user_id);

with bias (user_id, value) as (
  values
    ('00000000-0000-4000-a000-000000000001'::uuid, 0.3),
    ('00000000-0000-4000-a000-000000000002'::uuid, 0.8),
    ('00000000-0000-4000-a000-000000000003'::uuid, 0.0),
    ('00000000-0000-4000-a000-000000000004'::uuid, -1.0),
    ('00000000-0000-4000-a000-000000000005'::uuid, 0.2)
)
insert into public.votes (visit_id, group_id, user_id, category, value, created_at)
select
  sv.id, sv.group_id, p.user_id, c.category,
  least(10, greatest(1, round(
    case c.category
      when 'menjar' then sv.base_menjar
      when 'preu' then sv.base_preu
      when 'servei' then sv.base_servei
      else sv.base_espai
    end
    + b.value
    + ((abs(hashtext(sv.id::text || p.user_id::text || c.category::text)) % 5) - 2) * 0.5
  )))::smallint,
  sv.visit_date + time '22:50'
from seed_visits sv
cross join lateral unnest(sv.participants) as p(user_id)
join bias b on b.user_id = p.user_id
cross join unnest(enum_range(null::public.vote_category)) as c(category);

